import { useEffect, useState } from 'react';
import { Modal, View, Text, Pressable, ScrollView, StyleSheet, ActivityIndicator } from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import Check from '../assets/icons/check.svg';
import ChevronDown from '../assets/icons/chevron-down.svg';
import Calendar from '../assets/icons/calendar.svg';
import DateRangePickerModal from './DateRangePickerModal';
import { downloadAndShare } from '../utils/downloadFile';
import { attendanceExportUrl, XLSX_MIME } from '../services/exportService';
import { Colors, Fonts, Spacing, Radii } from '../constants/theme';

const MONTHS_ABBR = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
// "30 Mar 2024" -> "2024-03-30"
const toISO = (s) => {
  const m = /^(\d{1,2})\s+([A-Za-z]{3})\s+(\d{4})$/.exec(s || '');
  if (!m) return undefined;
  const mon = MONTHS_ABBR.findIndex((x) => x.toLowerCase() === m[2].toLowerCase());
  if (mon < 0) return undefined;
  return `${m[3]}-${String(mon + 1).padStart(2, '0')}-${String(Number(m[1])).padStart(2, '0')}`;
};

/**
 * Export Attendance Logs bottom-sheet (Figma 598-117030): pick child(ren) — the
 * dropdown is scoped to the chosen room(s), or all children when none — a date
 * range, rooms and status. Exports an XLSX generated by the backend.
 *
 * @param {Array}  childList [{ id, name, roomId, room }]
 * @param {Array}  rooms     [{ id, name }]
 * @param {string} token     Bearer token for the download
 */
export default function ExportAttendanceModal({ visible, childList = [], rooms = [], token, onClose, onDownloaded }) {
  const [selectedIds, setSelectedIds] = useState([]);
  const [childOpen, setChildOpen] = useState(false);
  const [range, setRange] = useState(null); // { from, to } "DD MMM YYYY"
  const [showRange, setShowRange] = useState(false);
  const [selectedRoomIds, setSelectedRoomIds] = useState([]);
  const [selectedStatus, setSelectedStatus] = useState([]); // 'Present' | 'Absent'
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    if (!visible) return;
    setSelectedIds([]);
    setChildOpen(false);
    setRange(null);
    setSelectedRoomIds([]);
    setSelectedStatus([]);
    setBusy(false);
  }, [visible]);

  // The dropdown lists children in the chosen rooms (all children when no room).
  const displayed = childList.filter(
    (c) => selectedRoomIds.length === 0 || selectedRoomIds.includes(c.roomId)
  );
  const chosen = selectedIds.filter((id) => displayed.some((c) => c.id === id));
  const allSelected = displayed.length > 0 && chosen.length === displayed.length;

  const toggleAll = () =>
    setSelectedIds(allSelected ? [] : displayed.map((c) => c.id));
  const toggleChild = (id) =>
    setSelectedIds((cur) => (cur.includes(id) ? cur.filter((x) => x !== id) : [...cur, id]));
  const toggleRoom = (id) =>
    setSelectedRoomIds((cur) => (cur.includes(id) ? cur.filter((x) => x !== id) : [...cur, id]));
  const toggleStatus = (s) =>
    setSelectedStatus((cur) => (cur.includes(s) ? cur.filter((x) => x !== s) : [...cur, s]));

  const childLabel = allSelected
    ? 'All Children'
    : chosen.length > 0
      ? `${chosen.length} selected`
      : 'Select child name';
  const dateLabel = range ? `${range.from} - ${range.to}` : 'Select date range';

  const doExport = async () => {
    if (busy) return;
    setBusy(true);
    const useSpecific = !allSelected && chosen.length > 0;
    const url = attendanceExportUrl({
      childIds: useSpecific ? chosen : [],
      roomIds: selectedRoomIds,
      from: range ? toISO(range.from) : undefined,
      to: range ? toISO(range.to) : undefined,
      statuses: selectedStatus.map((s) => (s === 'Present' ? 'PRESENT' : 'ABSENT')),
    });
    const ok = await downloadAndShare(url, 'attendance-logs.xlsx', XLSX_MIME, token);
    setBusy(false);
    if (ok) {
      onClose?.();
      onDownloaded?.();
    }
  };

  return (
    <>
    <Modal visible={visible} transparent animationType="slide" statusBarTranslucent onRequestClose={onClose}>
      <View style={styles.overlay}>
        <Pressable style={StyleSheet.absoluteFill} onPress={onClose} />

        <View style={styles.sheet}>
          <SafeAreaView edges={['bottom']}>
            <View style={styles.content}>
              <View style={styles.head}>
                <Text style={styles.title}>Export Attendance Logs</Text>
              </View>

              <ScrollView showsVerticalScrollIndicator={false}>
                {/* By child */}
                <View style={styles.section}>
                  <Text style={styles.sectionLabel}>By child</Text>
                  <Pressable style={styles.field} onPress={() => setChildOpen((o) => !o)}>
                    <Text style={[styles.fieldText, chosen.length === 0 && !allSelected && styles.placeholder]}>
                      {childLabel}
                    </Text>
                    <ChevronDown width={24} height={24} style={childOpen ? styles.chevronUp : undefined} />
                  </Pressable>
                  {childOpen && (
                    <View style={styles.dropdown}>
                      <ScrollView style={{ maxHeight: 240 }} nestedScrollEnabled showsVerticalScrollIndicator={false}>
                        <Pressable style={styles.childRow} onPress={toggleAll}>
                          <Text style={styles.childName}>All Children</Text>
                          <View style={[styles.checkbox, allSelected && styles.checkboxOn]}>
                            {allSelected && <Check width={16} height={16} />}
                          </View>
                        </Pressable>
                        {displayed.map((c) => {
                          const on = selectedIds.includes(c.id);
                          return (
                            <Pressable key={c.id} style={styles.childRow} onPress={() => toggleChild(c.id)}>
                              <View style={styles.childInfo}>
                                <Text style={styles.childName}>{c.name}</Text>
                                <Text style={styles.childSub}>{c.room}</Text>
                              </View>
                              <View style={[styles.checkbox, on && styles.checkboxOn]}>
                                {on && <Check width={16} height={16} />}
                              </View>
                            </Pressable>
                          );
                        })}
                        {displayed.length === 0 && <Text style={styles.emptyRow}>No children.</Text>}
                      </ScrollView>
                    </View>
                  )}
                </View>

                {/* By date range */}
                <View style={styles.section}>
                  <Text style={styles.sectionLabel}>By Date Range</Text>
                  <Pressable style={styles.field} onPress={() => setShowRange(true)}>
                    <Text style={[styles.fieldText, !range && styles.placeholder]}>{dateLabel}</Text>
                    <Calendar width={24} height={24} />
                  </Pressable>
                </View>

                {/* By rooms */}
                <View style={styles.section}>
                  <Text style={styles.sectionLabel}>By Rooms</Text>
                  <View style={styles.chipRow}>
                    {rooms.map((r) => {
                      const on = selectedRoomIds.includes(r.id);
                      return (
                        <Pressable key={r.id} style={[styles.chip, on && styles.chipOn]} onPress={() => toggleRoom(r.id)}>
                          <Text style={[styles.chipText, on && styles.chipTextOn]}>{r.name}</Text>
                        </Pressable>
                      );
                    })}
                  </View>
                </View>

                {/* By status */}
                <View style={styles.sectionLast}>
                  <Text style={styles.sectionLabel}>By Status</Text>
                  <View style={styles.chipRow}>
                    {['Present', 'Absent'].map((s) => {
                      const on = selectedStatus.includes(s);
                      return (
                        <Pressable key={s} style={[styles.chip, on && styles.chipOn]} onPress={() => toggleStatus(s)}>
                          <Text style={[styles.chipText, on && styles.chipTextOn]}>{s}</Text>
                        </Pressable>
                      );
                    })}
                  </View>
                </View>
              </ScrollView>

              <Pressable style={[styles.cta, busy && styles.ctaDisabled]} onPress={doExport} disabled={busy}>
                {busy ? <ActivityIndicator color={Colors.background} /> : <Text style={styles.ctaText}>Export As XLSX</Text>}
              </Pressable>
            </View>
          </SafeAreaView>
        </View>
      </View>
    </Modal>

    <DateRangePickerModal
      visible={showRange}
      onClose={() => setShowRange(false)}
      onSelect={(r) => {
        setRange(r);
        setShowRange(false);
      }}
    />
    </>
  );
}

